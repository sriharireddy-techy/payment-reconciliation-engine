-- 01_schema_reference.sql  (REFERENCE ONLY - DO NOT RUN ON THE EXISTING SCHEMA)
--
-- The ten project tables exactly as designed in the team's Review 1 document
-- ("Database Implementation - DDL", tables 1-10, plus the two ALTER TABLE
-- statements). The live FreeSQL schema was compared with this file through
-- USER_TAB_COLUMNS and matches it column for column.
--
-- The application never runs this file. It is kept so the schema is versioned
-- with the code, and so a fresh, empty practice schema can be created if ever
-- needed. Running it where the tables already exist fails with ORA-00955 and
-- changes nothing.

CREATE TABLE USERS (
  user_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  full_name VARCHAR2(100) NOT NULL,
  email VARCHAR2(100) NOT NULL,
  phone_number VARCHAR2(15) NOT NULL,
  kyc_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_users PRIMARY KEY (user_id),
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT uq_users_phone UNIQUE (phone_number),
  CONSTRAINT chk_users_kyc CHECK (kyc_status IN ('PENDING','VERIFIED','REJECTED'))
);

CREATE TABLE PAYMENT_GATEWAYS (
  gateway_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  gateway_name VARCHAR2(50) NOT NULL,
  api_endpoint VARCHAR2(200) NOT NULL,
  settlement_currency VARCHAR2(3) DEFAULT 'INR' NOT NULL,
  fee_percentage NUMBER(5,2) DEFAULT 1.50 NOT NULL,
  gateway_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_gateways PRIMARY KEY (gateway_id),
  CONSTRAINT uq_gateway_name UNIQUE (gateway_name),
  CONSTRAINT chk_gateway_fee CHECK (fee_percentage BETWEEN 0 AND 100),
  CONSTRAINT chk_gateway_status CHECK (gateway_status IN ('ACTIVE','MAINTENANCE','INACTIVE'))
);

CREATE TABLE BANK_ACCOUNTS (
  account_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  user_id NUMBER NOT NULL,
  account_number VARCHAR2(20) NOT NULL,
  bank_name VARCHAR2(100) NOT NULL,
  ifsc_code VARCHAR2(11) NOT NULL,
  account_type VARCHAR2(20) DEFAULT 'SAVINGS' NOT NULL,
  current_balance NUMBER(15,2) DEFAULT 0 NOT NULL,
  currency VARCHAR2(3) DEFAULT 'INR' NOT NULL,
  account_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_bank_accounts PRIMARY KEY (account_id),
  CONSTRAINT fk_acc_user FOREIGN KEY (user_id) REFERENCES USERS(user_id),
  CONSTRAINT uq_account_number UNIQUE (account_number),
  CONSTRAINT chk_account_type CHECK (account_type IN ('SAVINGS','CURRENT')),
  CONSTRAINT chk_account_balance CHECK (current_balance >= 0),
  CONSTRAINT chk_account_currency CHECK (currency IN ('INR','USD','EUR','GBP')),
  CONSTRAINT chk_account_status CHECK (account_status IN ('ACTIVE','FROZEN','CLOSED'))
);

CREATE TABLE PAYMENT_PROFILES (
  profile_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  user_id NUMBER NOT NULL,
  preferred_gateway_id NUMBER,
  daily_limit NUMBER(15,2) DEFAULT 50000 NOT NULL,
  single_tx_limit NUMBER(15,2) DEFAULT 10000 NOT NULL,
  two_factor_auth VARCHAR2(1) DEFAULT 'Y' NOT NULL,
  profile_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_profiles PRIMARY KEY (profile_id),
  CONSTRAINT fk_profile_user FOREIGN KEY (user_id) REFERENCES USERS(user_id),
  CONSTRAINT uq_profile_user UNIQUE (user_id),
  CONSTRAINT fk_profile_gateway FOREIGN KEY (preferred_gateway_id) REFERENCES PAYMENT_GATEWAYS(gateway_id),
  CONSTRAINT chk_daily_limit CHECK (daily_limit >= 0),
  CONSTRAINT chk_single_limit CHECK (single_tx_limit >= 0),
  CONSTRAINT chk_two_factor CHECK (two_factor_auth IN ('Y','N')),
  CONSTRAINT chk_profile_status CHECK (profile_status IN ('ACTIVE','SUSPENDED'))
);

CREATE TABLE PAYMENT_TRANSACTIONS (
  transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  transaction_ref VARCHAR2(36) NOT NULL,
  idempotency_key VARCHAR2(100) NOT NULL,
  sender_account_id NUMBER NOT NULL,
  receiver_account_id NUMBER NOT NULL,
  gateway_id NUMBER,
  amount NUMBER(15,2) NOT NULL,
  fee_amount NUMBER(15,2) DEFAULT 0 NOT NULL,
  currency VARCHAR2(3) DEFAULT 'INR' NOT NULL,
  status VARCHAR2(20) DEFAULT 'INITIATED' NOT NULL,
  initiated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  completed_at TIMESTAMP,
  description VARCHAR2(255),
  CONSTRAINT pk_transactions PRIMARY KEY (transaction_id),
  CONSTRAINT uq_transaction_ref UNIQUE (transaction_ref),
  CONSTRAINT uq_idempotency_key UNIQUE (idempotency_key),
  CONSTRAINT fk_txn_sender FOREIGN KEY (sender_account_id) REFERENCES BANK_ACCOUNTS(account_id),
  CONSTRAINT fk_txn_receiver FOREIGN KEY (receiver_account_id) REFERENCES BANK_ACCOUNTS(account_id),
  CONSTRAINT fk_txn_gateway FOREIGN KEY (gateway_id) REFERENCES PAYMENT_GATEWAYS(gateway_id),
  CONSTRAINT chk_txn_amount CHECK (amount > 0),
  CONSTRAINT chk_txn_fee CHECK (fee_amount >= 0),
  CONSTRAINT chk_txn_status CHECK (status IN ('INITIATED','PROCESSING','SUCCESS','FAILED','REVERSED')),
  CONSTRAINT chk_different_accounts CHECK (sender_account_id <> receiver_account_id)
);

CREATE TABLE LEDGER_ENTRIES (
  entry_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  transaction_id NUMBER NOT NULL,
  account_id NUMBER NOT NULL,
  entry_type VARCHAR2(2) NOT NULL,
  amount NUMBER(15,2) NOT NULL,
  entry_timestamp TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  description VARCHAR2(200),
  CONSTRAINT pk_ledger PRIMARY KEY (entry_id),
  CONSTRAINT fk_ledger_txn FOREIGN KEY (transaction_id) REFERENCES PAYMENT_TRANSACTIONS(transaction_id),
  CONSTRAINT fk_ledger_account FOREIGN KEY (account_id) REFERENCES BANK_ACCOUNTS(account_id),
  CONSTRAINT chk_entry_type CHECK (entry_type IN ('DR','CR')),
  CONSTRAINT chk_ledger_amount CHECK (amount > 0)
);

CREATE TABLE EXTERNAL_TRANSACTIONS (
  ext_transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  gateway_id NUMBER NOT NULL,
  external_reference_id VARCHAR2(100) NOT NULL,
  internal_transaction_ref VARCHAR2(36),
  reported_amount NUMBER(15,2) NOT NULL,
  reported_fee NUMBER(15,2) DEFAULT 0 NOT NULL,
  reported_status VARCHAR2(20) NOT NULL,
  settlement_date DATE NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_external_txns PRIMARY KEY (ext_transaction_id),
  CONSTRAINT fk_external_gateway FOREIGN KEY (gateway_id) REFERENCES PAYMENT_GATEWAYS(gateway_id),
  CONSTRAINT uq_gateway_external_ref UNIQUE (gateway_id, external_reference_id),
  CONSTRAINT chk_reported_amount CHECK (reported_amount > 0),
  CONSTRAINT chk_reported_fee CHECK (reported_fee >= 0),
  CONSTRAINT chk_reported_status CHECK (reported_status IN ('SUCCESS','FAILURE','PENDING','REFUNDED'))
);

CREATE TABLE RECONCILIATION_BATCHES (
  batch_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  gateway_id NUMBER NOT NULL,
  batch_date DATE NOT NULL,
  total_records NUMBER(8) DEFAULT 0 NOT NULL,
  matched_records NUMBER(8) DEFAULT 0 NOT NULL,
  exception_records NUMBER(8) DEFAULT 0 NOT NULL,
  batch_status VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
  execution_timestamp TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_recon_batches PRIMARY KEY (batch_id),
  CONSTRAINT fk_batch_gateway FOREIGN KEY (gateway_id) REFERENCES PAYMENT_GATEWAYS(gateway_id),
  CONSTRAINT chk_batch_total CHECK (total_records >= 0),
  CONSTRAINT chk_batch_matched CHECK (matched_records >= 0),
  CONSTRAINT chk_batch_exceptions CHECK (exception_records >= 0),
  CONSTRAINT chk_batch_status CHECK (batch_status IN ('OPEN','PROCESSING','COMPLETED','FAILED'))
);

CREATE TABLE RECONCILIATION_EXCEPTIONS (
  exception_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  batch_id NUMBER NOT NULL,
  internal_transaction_id NUMBER,
  ext_transaction_id NUMBER,
  exception_type VARCHAR2(30) NOT NULL,
  discrepancy_amount NUMBER(15,2) DEFAULT 0 NOT NULL,
  resolution_status VARCHAR2(20) DEFAULT 'UNRESOLVED' NOT NULL,
  resolution_notes VARCHAR2(500),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_recon_exceptions PRIMARY KEY (exception_id),
  CONSTRAINT fk_exception_batch FOREIGN KEY (batch_id) REFERENCES RECONCILIATION_BATCHES(batch_id),
  CONSTRAINT fk_exception_internal FOREIGN KEY (internal_transaction_id) REFERENCES PAYMENT_TRANSACTIONS(transaction_id),
  CONSTRAINT fk_exception_external FOREIGN KEY (ext_transaction_id) REFERENCES EXTERNAL_TRANSACTIONS(ext_transaction_id),
  CONSTRAINT chk_exception_type CHECK (exception_type IN
    ('AMOUNT_MISMATCH','STATUS_MISMATCH','MISSING_IN_GATEWAY','MISSING_IN_INTERNAL')),
  CONSTRAINT chk_resolution_status CHECK (resolution_status IN
    ('UNRESOLVED','MANUALLY_RESOLVED','AUTO_RESOLVED','WRITTEN_OFF'))
);

CREATE TABLE AUDIT_LOGS (
  log_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  table_name VARCHAR2(50) NOT NULL,
  action_type VARCHAR2(10) NOT NULL,
  record_id NUMBER NOT NULL,
  account_id NUMBER,
  transaction_id NUMBER,
  performed_by VARCHAR2(50) DEFAULT USER NOT NULL,
  action_timestamp TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  details VARCHAR2(4000),
  CONSTRAINT pk_audit_logs PRIMARY KEY (log_id),
  CONSTRAINT chk_audit_action CHECK (action_type IN ('INSERT','UPDATE','DELETE','SECURITY')),
  CONSTRAINT fk_audit_account FOREIGN KEY (account_id) REFERENCES BANK_ACCOUNTS(account_id),
  CONSTRAINT fk_audit_transaction FOREIGN KEY (transaction_id) REFERENCES PAYMENT_TRANSACTIONS(transaction_id)
);

